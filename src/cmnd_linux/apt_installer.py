"""APT-managed CMND 0.8 activation.

Versioned Debian packages place tooling, exact Philips inputs and pinned Tomcat
on disk first. This module inventories the host, selects coexistence modes,
prepares runtime images and hands activation to coexist_deploy. Database admin
passwords are accepted only through root-only temporary files and never persisted.
"""
